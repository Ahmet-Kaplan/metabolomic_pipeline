"""Variance-heterogeneity diagnostic — Levene's test per feature.

The multiverse's univariate analysis uses parametric one-way ANOVA.
With n=6-7 per group and 4,644 features, the 63-69% significance rate
may be partly driven by unequal group variances rather than mean
differences. This script quantifies that risk via Levene's test.

Usage
-----
    uv run python scripts/diagnose_variance_heterogeneity.py

Writes a markdown report to ``docs/evaluation/variance_heterogeneity_check.md``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats as sp_stats

INTERIM = Path("data/interim")
REPORT = Path("docs/evaluation/variance_heterogeneity_check.md")

# Levene's test interpretation thresholds
LEVENE_P_THRESHOLD = 0.05


def load_data() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load the Stage-10 matrix and samples table."""
    samples = pd.read_parquet(INTERIM / "01_parsed/samples.parquet")
    kept = pd.read_parquet(INTERIM / "10_origin/kept_features.parquet")
    abund = pd.read_parquet(INTERIM / "01_parsed/abundances_raw_long.parquet")

    kept_ids = set(kept["feature_id"])
    abund = abund[abund["feature_id"].isin(kept_ids)]
    return abund, samples


def compute_levene(abund: pd.DataFrame, samples: pd.DataFrame) -> pd.DataFrame:
    """Per-feature Levene's test for equal variances across cell-line groups.

    Levene's test is used (not Bartlett's) because it is robust to
    non-normality. Returns one row per feature with the test statistic,
    p-value, and group standard deviations.
    """
    bio = samples[samples["injection_type"] == "biological"][["sample_id", "cell_line"]]
    bio_ids = set(bio["sample_id"])

    df = abund[abund["sample_id"].isin(bio_ids)].merge(
        bio, on="sample_id", how="left"
    )
    df["intensity"] = pd.to_numeric(df["intensity"], errors="coerce")

    rows: list[dict] = []
    for fid, group in df.groupby("feature_id", sort=False):
        groups: dict[str, np.ndarray] = {}
        for cell_line, sub in group.groupby("cell_line"):
            vals = sub["intensity"].dropna().to_numpy(dtype=float)
            vals = vals[vals > 0]
            if len(vals) >= 2:
                groups[cell_line] = np.log2(vals)

        if len(groups) < 2:
            continue

        sample_groups = list(groups.values())
        stat, pval = sp_stats.levene(*sample_groups)

        stds = {f"std_{g}": float(v.std(ddof=1)) for g, v in groups.items()}
        max_std_ratio = 1.0
        std_list = [v.std(ddof=1) for v in sample_groups]
        if len(std_list) >= 2 and min(std_list) > 0:
            max_std_ratio = max(std_list) / min(std_list)

        rows.append({
            "feature_id": fid,
            "n_groups": len(groups),
            "levene_stat": float(stat),
            "levene_p": float(pval),
            "std_ratio_max_min": float(max_std_ratio),
            **stds,
        })

    return pd.DataFrame(rows)


def main() -> None:
    print("Loading data...")
    abund, samples = load_data()
    print(f"  {len(abund['feature_id'].unique()):,} features, "
          f"{len(abund):,} abundance rows")

    print("Computing Levene's test per feature...")
    results = compute_levene(abund, samples)
    print(f"  {len(results):,} features with >= 2 groups with >= 2 detections")

    n_violations = int((results["levene_p"] < LEVENE_P_THRESHOLD).sum())
    n_total = len(results)
    pct_violations = 100 * n_violations / n_total if n_total else 0

    median_ratio = float(results["std_ratio_max_min"].median())
    q95_ratio = float(results["std_ratio_max_min"].quantile(0.95))
    max_ratio = float(results["std_ratio_max_min"].max())

    lines = [
        "# Variance-heterogeneity diagnostic",
        "",
        "_Auto-generated by `scripts/diagnose_variance_heterogeneity.py`._",
        "",
        "Levene's test per feature (log2-transformed intensities) assesses "
        "whether the high 63-69% ANOVA significance rate is partly driven "
        "by unequal group variances rather than mean differences.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|--------|------:|",
        f"| Features tested | {n_total:,} |",
        f"| Features with unequal variances (p < {LEVENE_P_THRESHOLD}) | "
        f"{n_violations:,} ({pct_violations:.1f}%) |",
        f"| Median std ratio (max/min) | {median_ratio:.2f} |",
        f"| 95th percentile std ratio | {q95_ratio:.2f} |",
        f"| Max std ratio | {max_ratio:.2f} |",
        "",
    ]

    if pct_violations > 30:
        lines.append(
            "⚠️ **HIGH proportion of features with unequal variances.** "
            "This is common in metabolomics (different metabolites have "
            "different biological variances), but it means a portion of "
            "significant ANOVA results may reflect variance differences "
            "rather than mean shifts. The eta-squared effect sizes and "
            "Tukey HSD post-hoc tests should be inspected for these features."
        )
    elif pct_violations > 10:
        lines.append(
            "⚖️ **MODERATE proportion of features with unequal variances.** "
            "For the 10-30% affected features, inspect eta-squared and "
            "Tukey HSD to confirm mean differences are driving significance."
        )
    else:
        lines.append(
            "✅ **Low proportion of features with unequal variances.** "
            "Variance heterogeneity is unlikely to be driving the high "
            "significance rate."
        )

    lines += [
        "",
        "## Interpretation",
        "",
        "A significant Levene's test (p < 0.05) indicates that group "
        "variances differ. At n=6-7 per group, the F-test in ANOVA is "
        "moderately robust to variance heterogeneity when group sizes "
        "are approximately equal (which they are here: 6-7 per group). "
        "However, features with extreme std ratios (> 5) warrant manual "
        "inspection — their ANOVA p-values may be unreliable.",
        "",
        "## Recommendations",
        "",
        f"1. Features with Levene p < {LEVENE_P_THRESHOLD} AND std ratio > 5 "
        "should be flagged for manual inspection of group-wise distributions.",
        "2. The eta-squared effect size (already in the univariate output) "
        "should be the primary filter, not p-value alone — eta-squared is "
        "less sensitive to variance heterogeneity.",
        "3. For the 12 features in the consensus shortlist that are not the "
        "ganglioside, confirm their group variances are not driving the signal.",
        "",
    ]

    # Per-feature detail for shortlist features
    shortlist_path = Path("data/reports/multiverse/consensus_passed.parquet")
    if shortlist_path.exists():
        shortlist = pd.read_parquet(shortlist_path)
        sl_features = set(shortlist["feature_id"])
        sl_in_results = results[results["feature_id"].isin(sl_features)]

        if not sl_in_results.empty:
            lines += [
                "## Variance heterogeneity in consensus shortlist features",
                "",
                "| feature_id | Levene p | std ratio | groups |",
                "|------------|---------:|----------:|------:|",
            ]
            for _, r in sl_in_results.sort_values("levene_p").iterrows():
                lines.append(
                    f"| {r['feature_id']} | {r['levene_p']:.4f} | "
                    f"{r['std_ratio_max_min']:.2f} | {r['n_groups']} |"
                )
            lines.append("")

    report = "\n".join(lines)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(report)
    print(report)
    print(f"\n[written] {REPORT}")


if __name__ == "__main__":
    main()
